# Bundles every service under dataExports/ into webapp/data.js for the dashboard.
# A service is included when dataExports/<service>/index.json exists and lists at least one item.
# For each index entry it reads <folder>/metadata.json and the content file it names (content.md).
# Rerun after every download (after build-index.ps1), or the dashboard shows the old data.
# Usage (from any folder): powershell -NoProfile -ExecutionPolicy Bypass -File scripts/build-dashboard-data.ps1
param(
    [string]$ExportsDir = (Join-Path $PSScriptRoot "../dataExports"),
    [string]$OutFile = (Join-Path $PSScriptRoot "../webapp/data.js")
)

$ErrorActionPreference = "Stop"
$exports = (Resolve-Path $ExportsDir).Path
$utf8 = New-Object System.Text.UTF8Encoding($false)
$textExtensions = @(".md", ".markdown", ".txt")

# JSON string literal for any text (ConvertTo-Json on a plain string in PowerShell 5.1 is fine for this).
function JsonString([string]$s) {
    if ($null -eq $s) { return "null" }
    return (ConvertTo-Json -InputObject $s -Compress)
}

$serviceParts = New-Object System.Collections.Generic.List[string]
$total = 0
foreach ($svcDir in Get-ChildItem -LiteralPath $exports -Directory | Sort-Object Name) {
    $indexPath = Join-Path $svcDir.FullName "index.json"
    if (-not (Test-Path -LiteralPath $indexPath)) { continue }
    $indexText = [System.IO.File]::ReadAllText($indexPath, $utf8)
    $index = $indexText | ConvertFrom-Json
    if (-not $index.pages -or @($index.pages).Count -eq 0) { continue }

    $itemParts = New-Object System.Collections.Generic.List[string]
    foreach ($entry in @($index.pages)) {
        $folder = Join-Path $svcDir.FullName $entry.folder
        $metaPath = Join-Path $folder "metadata.json"
        if (-not (Test-Path -LiteralPath $metaPath)) {
            Write-Warning "$($svcDir.Name): index.json lists $($entry.folder) but it has no metadata.json; skipped. Rerun build-index.ps1."
            continue
        }
        # metadata.json is JSON, so its text is embedded as-is (JSON is valid JavaScript).
        $metaText = [System.IO.File]::ReadAllText($metaPath, $utf8).Trim()
        $meta = $metaText | ConvertFrom-Json
        $contentFile = if ($meta.content_file) { [string]$meta.content_file } else { "content.md" }
        $contentPath = Join-Path $folder $contentFile
        $content = $null
        if ((Test-Path -LiteralPath $contentPath) -and ($textExtensions -contains [System.IO.Path]::GetExtension($contentFile).ToLowerInvariant())) {
            $content = [System.IO.File]::ReadAllText($contentPath, $utf8) -replace "`r`n", "`n"
        }
        $itemParts.Add("{`"folder`":$(JsonString $entry.folder),`"metadata`":$metaText,`"content`":$(JsonString $content)}")
    }
    if ($itemParts.Count -eq 0) { continue }
    $total += $itemParts.Count
    Write-Host "$($svcDir.Name): $($itemParts.Count) items"
    $serviceParts.Add("{`"service`":$(JsonString $svcDir.Name),`"updated_at`":$(JsonString $index.updated_at),`"items`":[`n" + ($itemParts -join ",`n") + "`n]}")
}

$generated = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss.fffZ")
$js = "// GENERATED by scripts/build-dashboard-data.ps1 - do not edit. Rerun the script after every download.`n" +
      "window.DASHBOARD_DATA = {`"generated_at`":`"$generated`",`"services`":[`n" + ($serviceParts -join ",`n") + "`n]};`n"

$outPath = [System.IO.Path]::GetFullPath([System.IO.Path]::Combine((Get-Location).Path, $OutFile))
[System.IO.File]::WriteAllText($outPath, $js, $utf8)
Write-Host "Wrote $outPath ($($serviceParts.Count) services, $total items)"
